export const pathOf = (job, id) => PATHS[job]?.[id] || null;
// 레벨에 열린 경지 수
export const nodesOpen = (lv) => PATH_NODE_LV.filter((x) => lv >= x).length;
// 합일 — 레벨 140 · 4차 전직
export const merged = (s) => !!s.path && s.level >= MERGE_LV && (s.jobTier || 0) >= 4;

// 지금 켜진 길 효과를 더해서 돌려준다
export function pathMods(s) {
  const out = {};
  if (!s?.job || !s.path || !PATHS[s.job]) return out;
  const add = (eff) => { for (const [k, v] of Object.entries(eff)) out[k] = (out[k] || 0) + v; };
  const n = nodesOpen(s.level);
  const mine = PATHS[s.job][s.path];
  mine.nodes.slice(0, n).forEach((nd) => add(nd.eff));
  if (merged(s)) {
    const other = PATHS[s.job][s.path === 'a' ? 'b' : 'a'];
    other.nodes.forEach((nd) => add(nd.eff));
  } else add(PATH_COST[s.path]);
  return out;
}
